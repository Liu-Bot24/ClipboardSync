import AppKit
import ClipboardSyncCore
import ImageIO

enum ClipboardWriteError: LocalizedError {
    case unsupportedContent(String)
    case invalidImage
    case imageTooLarge
    case pasteboardRejected

    var errorDescription: String? {
        switch self {
        case .unsupportedContent(let type): return "Unsupported clipboard content: \(type)"
        case .invalidImage: return "The image could not be decoded"
        case .imageTooLarge: return "The image exceeds the size limit"
        case .pasteboardRejected: return "The system clipboard rejected the write"
        }
    }
}

/// `NSPasteboard.general` for the sync engine. Reads happen only after the change
/// count moved, so an image on the clipboard is converted at most once per copy.
final class PasteboardBackend: ClipboardBackend {
    /// Types that ask clipboard tools not to record the content (nspasteboard.org).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    private let pasteboard: NSPasteboard
    /// Keeps the lazy TIFF provider of our last image write alive while it is on the pasteboard.
    private var tiffProvider: TIFFProvider?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var changeCount: Int { pasteboard.changeCount }

    func read(maxBytes: Int) throws -> ClipboardRead {
        guard let types = pasteboard.types, !types.isEmpty else { return .empty }
        if types.contains(where: Self.ignoredTypes.contains) { return .ignored }
        // A Finder file copy carries the file name as text and the icon as an image; neither is the file.
        if types.contains(.fileURL) { return .ignored }

        // Text wins when present: rich-text sources (Office, Pages) also attach a rendered image.
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            let snapshot = ClipboardSnapshot.text(text)
            return snapshot.byteLength > maxBytes ? .tooLarge(hash: snapshot.hash) : .snapshot(snapshot)
        }

        let limit = min(maxBytes, ImageRules.maxBytes)
        if let png = pasteboard.data(forType: .png) {
            guard let size = ImageSupport.pixelSize(of: png), ImageRules.dimensionsAllowed(width: size.width, height: size.height),
                  png.count <= limit
            else { return .tooLarge(hash: nil) }
            return .snapshot(.png(png))
        }
        if let tiff = pasteboard.data(forType: .tiff) {
            return ImageSupport.pngSnapshot(fromImageData: tiff, limit: limit)
        }
        // Other image types (JPEG, HEIC, PDF...) through NSImage.
        if pasteboard.canReadObject(forClasses: [NSImage.self], options: nil),
           let image = NSImage(pasteboard: pasteboard), let tiff = image.tiffRepresentation {
            return ImageSupport.pngSnapshot(fromImageData: tiff, limit: limit)
        }
        return .empty
    }

    func write(_ event: ClipboardEvent) throws -> Int {
        if event.isText {
            pasteboard.clearContents()
            tiffProvider = nil
            guard pasteboard.setString(event.content, forType: .string) else { throw ClipboardWriteError.pasteboardRejected }
            return pasteboard.changeCount
        }
        guard event.isImage, event.encoding == "base64" else { throw ClipboardWriteError.unsupportedContent(event.contentType) }
        guard event.content.utf8.count <= (ImageRules.maxBytes + 2) / 3 * 4,
              let data = Data(base64Encoded: event.content)
        else { throw ClipboardWriteError.imageTooLarge }
        guard ImageRules.signatureMatches(data, contentType: event.contentType),
              let size = ImageSupport.pixelSize(of: data)
        else { throw ClipboardWriteError.invalidImage }
        guard ImageRules.dimensionsAllowed(width: size.width, height: size.height) else { throw ClipboardWriteError.imageTooLarge }

        let png: Data
        if event.contentType == "image/png" {
            png = data
        } else {
            guard let converted = ImageSupport.pngData(fromImageData: data) else { throw ClipboardWriteError.invalidImage }
            png = converted
        }
        let item = NSPasteboardItem()
        item.setData(png, forType: .png)
        // Many apps still read TIFF; render it only if one asks.
        let provider = TIFFProvider(png: png)
        _ = item.setDataProvider(provider, forTypes: [.tiff])
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else {
            tiffProvider = nil
            throw ClipboardWriteError.pasteboardRejected
        }
        tiffProvider = provider
        return pasteboard.changeCount
    }
}

private final class TIFFProvider: NSObject, NSPasteboardItemDataProvider {
    private var png: Data?

    init(png: Data) {
        self.png = png
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .tiff, let png, let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation else { return }
        item.setData(tiff, forType: .tiff)
    }

    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {
        png = nil
    }
}

enum ImageSupport {
    /// Pixel size from the image header, without decoding the bitmap.
    static func pixelSize(of data: Data) -> (width: Int, height: Int)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int
        else { return nil }
        return (width, height)
    }

    static func pngData(fromImageData data: Data) -> Data? {
        NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
    }

    static func pngSnapshot(fromImageData data: Data, limit: Int) -> ClipboardRead {
        guard let rep = NSBitmapImageRep(data: data) else { return .empty }
        guard ImageRules.dimensionsAllowed(width: rep.pixelsWide, height: rep.pixelsHigh) else { return .tooLarge(hash: nil) }
        guard let png = rep.representation(using: .png, properties: [:]) else { return .empty }
        return png.count <= limit ? .snapshot(.png(png)) : .tooLarge(hash: nil)
    }

    /// Downscaled thumbnail decoded straight from the encoded data.
    static func thumbnail(of data: Data, maxPixelSize: Int) -> NSImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSImage(cgImage: image, size: NSSize(width: image.width, height: image.height))
    }
}

/// Bounded thumbnail cache for history rows and menu items.
final class ThumbnailCache {
    static let shared = ThumbnailCache()
    private let cache = NSCache<NSString, NSImage>()

    init() {
        cache.countLimit = 160
    }

    func thumbnail(for event: ClipboardEvent, maxPixelSize: Int) -> NSImage? {
        guard event.isImage else { return nil }
        let key = "\(event.id ?? event.payloadHash)#\(maxPixelSize)" as NSString
        if let cached = cache.object(forKey: key) { return cached }
        guard event.content.utf8.count <= (ImageRules.maxBytes + 2) / 3 * 4,
              let data = Data(base64Encoded: event.content),
              ImageRules.signatureMatches(data, contentType: event.contentType),
              let size = ImageSupport.pixelSize(of: data),
              ImageRules.dimensionsAllowed(width: size.width, height: size.height),
              let image = ImageSupport.thumbnail(of: data, maxPixelSize: maxPixelSize)
        else { return nil }
        cache.setObject(image, forKey: key)
        return image
    }

    func removeAll() {
        cache.removeAllObjects()
    }
}
